"""Agentic Collections server.

Serves the editorial review UI and its API:

  GET  /                              the UI
  GET  /api/collections               table data: name, thesis, item
                                      count (after removals), status
  GET  /api/collections/<id>          one collection with its items
  POST /api/collections/<id>/approve  mark a collection approved
  POST /api/collections/<id>/unapprove
  POST /api/collections/<id>/remove   {"tmdb_id": N} drop one item
  POST /api/collections/<id>/restore  {"tmdb_id": N} undo a removal
  POST /api/agent/run                 re-run the master agent crawl

Editorial decisions persist in data/editorial_state.json and survive
restarts. Collections themselves are regenerated by the master agent
into data/collections.json; re-running the agent never resurrects an
item the editors removed (removals are keyed by collection + tmdb_id).

Run:  python3 server.py [--port 8100]
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "agent"))

VERSION = "0.3.0"
COLLECTIONS_PATH = ROOT / "data" / "collections.json"
STATE_PATH = ROOT / "data" / "editorial_state.json"
STATIC_DIR = ROOT / "static"


def load_state() -> dict:
    if STATE_PATH.exists():
        try:
            return json.loads(STATE_PATH.read_text())
        except Exception:
            pass
    return {"approved": {}, "removed": {}}


def save_state(state: dict) -> None:
    STATE_PATH.write_text(json.dumps(state, indent=1))


def load_collections() -> dict:
    if not COLLECTIONS_PATH.exists():
        import master_agent
        master_agent.main()
    return json.loads(COLLECTIONS_PATH.read_text())


def find_collection(data: dict, cid: str):
    for c in data["collections"]:
        if c["id"] == cid:
            return c
    for tp in data.get("tentpoles", []):
        for c in tp["collections"]:
            if c["id"] == cid:
                return c
    return None


def collection_view(col: dict, state: dict) -> dict:
    removed = set(state.get("removed", {}).get(col["id"], []))
    items = [i for i in col["items"] if i["tmdb_id"] not in removed]
    return {
        "id": col["id"],
        "name": col["name"],
        "thesis": col["thesis"],
        "rule": col["rule"],
        "total_items": len(items),
        "removed_count": len(col["items"]) - len(items),
        "status": "approved" if state.get("approved", {}).get(col["id"]) else "pending",
    }


class Handler(BaseHTTPRequestHandler):
    server_version = "AgenticCollections/0.1"

    def log_message(self, fmt, *args):  # keep logs one-line and quiet
        sys.stderr.write("%s - %s\n" % (self.address_string(), fmt % args))

    # -- helpers ------------------------------------------------------
    def _send(self, code: int, body: bytes, ctype: str):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _json(self, code: int, obj):
        self._send(code, json.dumps(obj).encode(), "application/json")

    def _body(self) -> dict:
        try:
            n = int(self.headers.get("Content-Length") or 0)
            return json.loads(self.rfile.read(n) or b"{}")
        except Exception:
            return {}

    # -- routing ------------------------------------------------------
    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/api/collections":
            data = load_collections()
            state = load_state()
            return self._json(200, {
                "version": VERSION,
                "catalog_size": data["catalog_size"],
                "attribution": data["attribution"],
                "collections": [collection_view(c, state)
                                for c in data["collections"]],
            })
        if path == "/api/tentpoles":
            data = load_collections()
            state = load_state()
            events = []
            for tp in data.get("tentpoles", []):
                events.append({
                    "id": tp["id"], "name": tp["name"], "when": tp["when"],
                    "month": tp["month"], "day": tp["day"], "blurb": tp["blurb"],
                    "collections": [collection_view(c, state)
                                    for c in tp["collections"]],
                })
            return self._json(200, {"version": VERSION, "tentpoles": events})
        if path.startswith("/api/collections/"):
            cid = path.split("/")[3]
            data = load_collections()
            state = load_state()
            col = find_collection(data, cid)
            if not col:
                return self._json(404, {"error": "no such collection"})
            view = collection_view(col, state)
            removed = set(state.get("removed", {}).get(cid, []))
            view["items"] = [i for i in col["items"]
                             if i["tmdb_id"] not in removed]
            view["removed_items"] = [i for i in col["items"]
                                     if i["tmdb_id"] in removed]
            return self._json(200, view)
        # static files
        rel = "index.html" if path in ("/", "") else path.lstrip("/")
        target = (STATIC_DIR / rel).resolve()
        if target.is_file() and str(target).startswith(str(STATIC_DIR.resolve())):
            ctype = {".html": "text/html", ".css": "text/css",
                     ".js": "text/javascript"}.get(target.suffix, "text/plain")
            return self._send(200, target.read_bytes(), ctype)
        return self._json(404, {"error": "not found"})

    def do_POST(self):
        path = urlparse(self.path).path
        parts = [p for p in path.split("/") if p]
        state = load_state()

        if parts == ["api", "agent", "run"]:
            import master_agent
            master_agent.main()
            return self._json(200, {"ok": True})

        if len(parts) == 4 and parts[:2] == ["api", "collections"]:
            cid, action = parts[2], parts[3]
            if action == "approve":
                state.setdefault("approved", {})[cid] = True
            elif action == "unapprove":
                state.setdefault("approved", {}).pop(cid, None)
            elif action in ("remove", "restore"):
                tmdb_id = self._body().get("tmdb_id")
                if tmdb_id is None:
                    return self._json(400, {"error": "tmdb_id required"})
                removed = state.setdefault("removed", {}).setdefault(cid, [])
                if action == "remove" and tmdb_id not in removed:
                    removed.append(tmdb_id)
                if action == "restore" and tmdb_id in removed:
                    removed.remove(tmdb_id)
            else:
                return self._json(404, {"error": "unknown action"})
            save_state(state)
            data = load_collections()
            col = find_collection(data, cid)
            if not col:
                return self._json(404, {"error": "no such collection"})
            return self._json(200, collection_view(col, state))
        return self._json(404, {"error": "not found"})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int,
                    default=int(os.environ.get("PORT", 8100)))
    args = ap.parse_args()
    load_collections()  # build on first boot if needed
    srv = ThreadingHTTPServer(("0.0.0.0", args.port), Handler)
    print(f"Agentic Collections v{VERSION} on http://localhost:{args.port}")
    srv.serve_forever()


if __name__ == "__main__":
    main()
